// generates src/generated/template-manifest.ts: a content digest for every
// tracked file in templates/base-app, keyed by the CLI version whose tag the
// template is fetched from. fetch-template.ts refuses to extract a downloaded
// tarball whose files do not match these digests, so a republished/compromised
// GitHub tag cannot silently ship code into new projects.
//
// the manifest is regenerated on every `pnpm build` (and again during release
// after the template versions are synced) so it always reflects the exact tree
// that will be tagged and published.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(cliRoot, "../..");
const templateDir = path.join(repoRoot, "templates/base-app");
const outputFile = path.join(cliRoot, "src/generated/template-manifest.ts");

const { version } = JSON.parse(fs.readFileSync(path.join(cliRoot, "package.json"), "utf-8"));

const EXCLUDED_DIRS = new Set(["node_modules", "dist", ".anaemia", ".rspack", ".git"]);

function walk(dir) {
  const files = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (EXCLUDED_DIRS.has(entry.name)) continue;
        stack.push(full);
      } else if (entry.isFile()) {
        files.push(full);
      }
    }
  }
  return files;
}

function listTemplateFiles() {
  try {
    const out = execFileSync("git", ["-C", repoRoot, "ls-files", "--", "templates/base-app"], {
      encoding: "utf-8",
    });
    const tracked = out
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean)
      // only include files that actually exist in the working tree (a tracked
      // file can be deleted locally, in which case it is not in the tarball).
      .filter((rel) => fs.existsSync(path.join(repoRoot, rel)));
    if (tracked.length > 0) return tracked;
  } catch {
    // not a git checkout (e.g. building from a source tarball): fall back to a
    // plain walk. untracked/ignored directories are excluded above.
  }
  return walk(templateDir).map((abs) => path.relative(repoRoot, abs).split(path.sep).join("/"));
}

function digest(file) {
  return createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

const files = {};
for (const tracked of listTemplateFiles()) {
  const absolute = path.join(repoRoot, tracked);
  const relative = path.relative(templateDir, absolute).split(path.sep).join("/");
  files[relative] = digest(absolute);
}

const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));

const banner = `// AUTO-GENERATED by scripts/generate-template-manifest.mjs. do not edit by hand.
// regenerate with \`pnpm --filter @anaemia/cli generate:template-manifest\` (or any build).
`;

const filesJson = JSON.stringify(sorted, null, 2)
  .split("\n")
  .map((line, index) => (index === 0 ? line : "  " + line))
  .join("\n");

const body = `export const TEMPLATE_INTEGRITY: { version: string; files: Record<string, string> } = {
  version: ${JSON.stringify(version)},
  files: ${filesJson},
};
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, banner + body, "utf-8");
console.log(`wrote ${path.relative(repoRoot, outputFile)} (${Object.keys(sorted).length} files, v${version})`);
